def yaml_list(values):
    return json.dumps(values, ensure_ascii=False)


def front_matter(item, owner_role, artifact_types):
    outcome_ru = f"Создать: {item['product_ru']}."
    outcome_kk = f"Жасау: {item['product_kk']}."
    lines = [
        "---",
        f"lesson_id: {item['id']}",
        f"slug: {item['slug']}",
        "status: draft",
        "version: 0.1.0",
        "languages: [ru, kk]",
        "estimated_video_seconds: 120-180",
        "prerequisites: []",
        f"learning_outcomes: {yaml_list([outcome_ru, outcome_kk])}",
        f"artifact_types: {yaml_list(artifact_types)}",
        "mini_quiz: false",
        f"owner_role: {owner_role}",
        "---",
        "",
    ]
    return "\n".join(lines)


