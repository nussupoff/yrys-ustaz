def build_assignment(item):
    return (
        front_matter(item, "prompt-practice", item["artifact_types"])
        + f"# {item['id']}: {item['title_ru']} / {item['title_kk']}\n"
        + assignment_ru(item)
        + "\n"
        + assignment_kk(item)
    ).rstrip() + "\n"


def validate_lesson(item, prompts_text, assignment_text):
    for index in range(1, 13):
        prompt_id = f"P-{item['id']}-{index:02d}"
        if prompt_id not in prompts_text:
            raise ValueError(f"Missing prompt ID: {prompt_id}")

    required_fields = [SUBJECT, GRADE, TOPIC, GOAL, LANGUAGE]
    for field in required_fields:
        if prompts_text.count(field) < 12:
            raise ValueError(
                f"{item['id']}: field {field} must appear in every prompt"
            )

    if prompts_text.count(FENCE + "text") != 12:
        raise ValueError(f"{item['id']}: expected exactly 12 prompt code blocks")

    assignment_id = f"A-{item['id']}-01"
    if assignment_id not in assignment_text:
        raise ValueError(f"Missing assignment ID: {assignment_id}")

    for artifact_type in item["artifact_types"]:
        if artifact_type not in assignment_text:
            raise ValueError(
                f"{item['id']}: artifact type {artifact_type} missing from assignment"
            )


def write_course(root):
    lessons_root = root / "lessons"
    lessons_root.mkdir(parents=True, exist_ok=True)

    for item in LESSONS:
        lesson_dir = lessons_root / item["id"]
        lesson_dir.mkdir(parents=True, exist_ok=True)

        prompts_text = build_prompts(item)
        assignment_text = build_assignment(item)
        validate_lesson(item, prompts_text, assignment_text)

        (lesson_dir / "prompts.md").write_text(
            prompts_text,
            encoding="utf-8",
            newline="\n",
        )
        (lesson_dir / "assignment.md").write_text(
            assignment_text,
            encoding="utf-8",
            newline="\n",
        )


def main():
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("course")
    write_course(root)
    print(
        f"Созданы prompts.md и assignment.md для {len(LESSONS)} уроков "
        f"в каталоге: {root.resolve()}"
    )


if __name__ == "__main__":
    main()