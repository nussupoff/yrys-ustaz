def build_prompts(item):
    content = [
        front_matter(item, "prompt-practice", item["artifact_types"]),
        f"# {item['id']}: {item['title_ru']} / {item['title_kk']}",
        "",
        "## Русский",
        "",
    ]

    ru = ru_prompts(item)
    kk = kk_prompts(item)

    for index, prompt in enumerate(ru, start=1):
        prompt_id = f"P-{item['id']}-{index:02d}"
        equivalent_id = f"P-{item['id']}-{index + 6:02d}"
        content.append(prompt_entry(
            prompt_id,
            equivalent_id,
            prompt["purpose"],
            prompt["when"],
            prompt["expected"],
            prompt["criterion"],
            prompt["text"],
        ))

    content.extend([
        "## Қазақша",
        "",
    ])

    for index, prompt in enumerate(kk, start=7):
        prompt_id = f"P-{item['id']}-{index:02d}"
        equivalent_id = f"P-{item['id']}-{index - 6:02d}"
        content.append(prompt_entry(
            prompt_id,
            equivalent_id,
            prompt["purpose"],
            prompt["when"],
            prompt["expected"],
            prompt["criterion"],
            prompt["text"],
        ))

    return "\n".join(content).rstrip() + "\n"


def format_labels(types, language):
    ru = {
        "file": "file — файл",
        "link": "link — ссылка",
        "screenshot": "screenshot — скриншот",
        "text": "text — текст",
    }
    kk = {
        "file": "file — файл",
        "link": "link — сілтеме",
        "screenshot": "screenshot — скриншот",
        "text": "text — мәтін",
    }
    mapping = ru if language == "ru" else kk
    return ", ".join(mapping[value] for value in types)


