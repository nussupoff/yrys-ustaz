def narration_text(segments: List[Dict[str, str]]) -> str:
    return "\n".join(segment["voice"] for segment in segments)


def validate_segments(
    lesson_id: str,
    language: str,
    segments: List[Dict[str, str]],
) -> Dict[str, int]:
    if len(segments) != 7:
        raise ValueError(
            f"{lesson_id} {language}: ожидалось 7 сегментов, получено {len(segments)}"
        )

    required_fields = {"visual", "voice", "screen", "note"}
    for index, segment in enumerate(segments, start=1):
        missing = required_fields.difference(segment)
        if missing:
            raise ValueError(
                f"{lesson_id} {language}, сегмент {index}: отсутствуют поля {sorted(missing)}"
            )
        for field in required_fields:
            if not segment[field].strip():
                raise ValueError(
                    f"{lesson_id} {language}, сегмент {index}: пустое поле {field}"
                )

    full_voice = narration_text(segments)
    words = word_count(full_voice)

    # Обязательная жёсткая граница: validate падает ниже 260 или выше 380.
    if words < HARD_MIN_WORDS or words > MAX_WORDS:
        raise ValueError(
            f"{lesson_id} {language}: дикторский текст содержит {words} слов; "
            f"допустимая жёсткая граница {HARD_MIN_WORDS}–{MAX_WORDS}"
        )

    # Производственный диапазон задания строже: готовые сценарии должны иметь 280–380 слов.
    if words < TARGET_MIN_WORDS:
        raise ValueError(
            f"{lesson_id} {language}: получено {words} слов; "
            f"целевой диапазон начинается с {TARGET_MIN_WORDS}"
        )

    seconds = estimated_duration_seconds(words)
    if seconds < MIN_DURATION_SECONDS or seconds > MAX_DURATION_SECONDS:
        raise ValueError(
            f"{lesson_id} {language}: расчётная длительность {seconds} сек. "
            f"при {WORDS_PER_MINUTE} слов/мин; допустимо "
            f"{MIN_DURATION_SECONDS}–{MAX_DURATION_SECONDS} сек."
        )

    if language == "RU" and "[НУЖНА ПРОВЕРКА]" not in (
        full_voice + " ".join(s["visual"] + s["note"] for s in segments)
    ):
        raise ValueError(f"{lesson_id} RU: отсутствует маркер [НУЖНА ПРОВЕРКА]")

    if language == "KK" and "[ТЕКСЕРУ ҚАЖЕТ]" not in (
        full_voice + " ".join(s["visual"] + s["note"] for s in segments)
    ):
        raise ValueError(f"{lesson_id} KK: отсутствует маркер [ТЕКСЕРУ ҚАЖЕТ]")

    return {"words": words, "seconds": seconds}


def render_table(segments: List[Dict[str, str]]) -> str:
    lines = [
        "| Время | Визуал / скринкаст | Дикторский текст | Экранный текст | Примечание монтажу |",
        "|---|---|---|---|---|",
    ]

    for timecode, segment in zip(TIMECODES, segments):
        label = timecode[0]
        lines.append(
            "| "
            + " | ".join(
                [
                    label,
                    cell(segment["visual"]),
                    cell(segment["voice"]),
                    cell(segment["screen"]),
                    cell(segment["note"]),
                ]
            )
            + " |"
        )

    return "\n".join(lines)


def render_document(
    lesson: Dict[str, str],
    ru_segments: List[Dict[str, str]],
    kk_segments: List[Dict[str, str]],
    ru_metrics: Dict[str, int],
    kk_metrics: Dict[str, int],
) -> str:
    max_seconds = max(ru_metrics["seconds"], kk_metrics["seconds"])

    front_matter = f"""---
lesson_id: {lesson["lesson_id"]}
slug: {lesson["slug"]}
status: {STATUS}
version: {VERSION}
languages: [ru, kk]
estimated_video_seconds: {max_seconds}
prerequisites: []
learning_outcomes:
  - {yaml_quote(lesson["ru_result"])}
  - {yaml_quote(lesson["kk_result"])}
artifact_types: [file, screenshot, text]
mini_quiz: false
owner_role: {OWNER_ROLE}
narration_metrics:
  ru:
    words: {ru_metrics["words"]}
    estimated_seconds: {ru_metrics["seconds"]}
    calculation: {yaml_quote(f'{ru_metrics["words"]} слов / {WORDS_PER_MINUTE} слов/мин')}
  kk:
    words: {kk_metrics["words"]}
    estimated_seconds: {kk_metrics["seconds"]}
    calculation: {yaml_quote(f'{kk_metrics["words"]} сөз / {WORDS_PER_MINUTE} сөз/мин')}
---
"""

    return (
        front_matter
        + "\n"
        + f"# {lesson['lesson_id']}. {lesson['ru_title']} / {lesson['kk_title']}\n\n"
        + "## RU\n\n"
        + render_table(ru_segments)
        + "\n\n"
        + "### Хронометраж RU\n\n"
        + f"- Дикторский текст: **{ru_metrics['words']} слов**.\n"
        + f"- Расчёт: {ru_metrics['words']} / {WORDS_PER_MINUTE} × 60 = "
        + f"**{ru_metrics['seconds']} секунд**.\n"
        + f"- Плановая шкала монтажа: **{TIMECODES[-1][0].split('–')[1]}**.\n\n"
        + "## KK\n\n"
        + render_table(kk_segments)
        + "\n\n"
        + "### KK хронометражы\n\n"
        + f"- Диктор мәтіні: **{kk_metrics['words']} сөз**.\n"
        + f"- Есеп: {kk_metrics['words']} / {WORDS_PER_MINUTE} × 60 = "
        + f"**{kk_metrics['seconds']} секунд**.\n"
        + f"- Монтаждың жоспарлы шкаласы: **{TIMECODES[-1][0].split('–')[1]}**.\n"
    )


def lesson_from_tuple(row: Tuple[str, ...]) -> Dict[str, str]:
    keys = [
        "lesson_id",
        "slug",
        "ru_title",
        "kk_title",
        "ru_result",
        "kk_result",
        "ru_input",
        "kk_input",
        "ru_check",
        "kk_check",
        "ru_error",
        "kk_error",
    ]
    if len(row) != len(keys):
        raise ValueError(
            f"Некорректная запись урока {row[0] if row else 'UNKNOWN'}: "
            f"ожидалось {len(keys)} полей, получено {len(row)}"
        )
    return dict(zip(keys, row))


def validate_lesson_catalog() -> None:
    if len(LESSONS) != 36:
        raise ValueError(f"Ожидалось 36 уроков, получено {len(LESSONS)}")

    expected_ids = [f"L{i:02d}" for i in range(1, 37)]
    actual_ids = [row[0] for row in LESSONS]

    if actual_ids != expected_ids:
        raise ValueError(
            "ID уроков должны идти строго от L01 до L36.\n"
            f"Ожидалось: {expected_ids}\n"
            f"Получено: {actual_ids}"
        )

    slugs = [row[1] for row in LESSONS]
    if len(slugs) != len(set(slugs)):
        raise ValueError("Slug уроков должны быть уникальными")

    for slug in slugs:
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
            raise ValueError(f"Некорректный slug: {slug}")


def validate_document(
    lesson_id: str,
    document: str,
    ru_metrics: Dict[str, int],
    kk_metrics: Dict[str, int],
) -> None:
    required_markers = [
        "---",
        f"lesson_id: {lesson_id}",
        "languages: [ru, kk]",
        "owner_role: video-scriptwriter",
        "## RU",
        "## KK",
        "[НУЖНА ПРОВЕРКА]",
        "[ТЕКСЕРУ ҚАЖЕТ]",
        "Типичная ошибка",
        "Жиі кездесетін қате",
        "Практика",
    ]
    for marker in required_markers:
        if marker not in document:
            raise ValueError(f"{lesson_id}: в документе отсутствует маркер {marker!r}")

    table_header_count = document.count(
        "| Время | Визуал / скринкаст | Дикторский текст | "
        "Экранный текст | Примечание монтажу |"
    )
    if table_header_count != 2:
        raise ValueError(
            f"{lesson_id}: ожидалось две таблицы сценария, найдено {table_header_count}"
        )

    for language, metrics in (("RU", ru_metrics), ("KK", kk_metrics)):
        words = metrics["words"]
        seconds = metrics["seconds"]
        if not TARGET_MIN_WORDS <= words <= MAX_WORDS:
            raise ValueError(
                f"{lesson_id} {language}: итоговый диапазон слов нарушен: {words}"
            )
        if not MIN_DURATION_SECONDS <= seconds <= MAX_DURATION_SECONDS:
            raise ValueError(
                f"{lesson_id} {language}: итоговый хронометраж нарушен: {seconds}"
            )


def generate_all() -> None:
    validate_lesson_catalog()
    written: List[Path] = []

    for row in LESSONS:
        lesson = lesson_from_tuple(row)
        lesson_id = lesson["lesson_id"]

        ru_segments = make_ru_segments(lesson)
        kk_segments = make_kk_segments(lesson)

        ru_metrics = validate_segments(lesson_id, "RU", ru_segments)
        kk_metrics = validate_segments(lesson_id, "KK", kk_segments)

        document = render_document(
            lesson,
            ru_segments,
            kk_segments,
            ru_metrics,
            kk_metrics,
        )
        validate_document(lesson_id, document, ru_metrics, kk_metrics)

        lesson_dir = OUTPUT_ROOT / lesson_id
        lesson_dir.mkdir(parents=True, exist_ok=True)
        output_path = lesson_dir / "video-script.md"
        output_path.write_text(document, encoding="utf-8", newline="\n")
        written.append(output_path)

        print(
            f"{lesson_id}: RU {ru_metrics['words']} слов / "
            f"{ru_metrics['seconds']} сек.; "
            f"KK {kk_metrics['words']} сөз / "
            f"{kk_metrics['seconds']} сек. -> {output_path}"
        )

    if len(written) != 36:
        raise RuntimeError(f"Записано {len(written)} файлов вместо 36")

    print(f"Готово: создано {len(written)} файлов video-script.md.")


def main() -> None:
    generate_all()


if __name__ == "__main__":
    main()