def word_count(text: str) -> int:
    """Считает слова в русском, казахском и латинском тексте."""
    pattern = (
        r"[0-9A-Za-zА-Яа-яЁё"
        r"ӘәҒғҚқҢңӨөҰұҮүҺһІі"
        r"]+(?:[-–—'’][0-9A-Za-zА-Яа-яЁё"
        r"ӘәҒғҚқҢңӨөҰұҮүҺһІі]+)*"
    )
    return len(re.findall(pattern, text, flags=re.UNICODE))


def estimated_duration_seconds(words: int) -> int:
    """
    Расчёт по реальному темпу 140 слов/мин.
    Здесь намеренно нет искусственного ограничения cap=180.
    """
    return round(words / WORDS_PER_MINUTE * 60)


