def validate():
    expected_ids = [f"L{i:02d}" for i in range(1, 37)]
    actual_ids = [item["id"] for item in LESSONS]
    if actual_ids != expected_ids:
        raise ValueError(f"Lesson IDs must be stable L01-L36, got: {actual_ids}")

    known = set(actual_ids)
    for item in LESSONS:
        if not item["topic_ru"] or not item["topic_kk"]:
            raise ValueError(f"Missing bilingual topic in {item['id']}")
        if not item["objective_ru"] or not item["objective_kk"]:
            raise ValueError(f"Missing bilingual objective in {item['id']}")
        if len(item["outcomes_ru"]) != len(item["outcomes_kk"]):
            raise ValueError(f"Outcome parity failure in {item['id']}")
        if len(item["steps_ru"]) != len(item["steps_kk"]):
            raise ValueError(f"Step parity failure in {item['id']}")
        if len(item["checks_ru"]) != len(item["checks_kk"]):
            raise ValueError(f"Readiness parity failure in {item['id']}")
        if not item["attachment_type"]:
            raise ValueError(f"Missing attachment type in {item['id']}")
        for prerequisite in item["prerequisites"]:
            if prerequisite not in known:
                raise ValueError(
                    f"Unknown prerequisite {prerequisite} in {item['id']}"
                )
            if prerequisite >= item["id"]:
                raise ValueError(
                    f"Prerequisite must precede lesson: "
                    f"{prerequisite} -> {item['id']}"
                )


