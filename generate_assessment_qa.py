def yaml_scalar(value: Any) -> str:
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, (int, float)):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)


def yaml_dump(value: Any, indent: int = 0) -> str:
    space = " " * indent

    if isinstance(value, dict):
        if not value:
            return "{}"
        lines: List[str] = []
        for key, item in value.items():
            safe_key = str(key) if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_-]*", str(key)) else yaml_scalar(key)
            if isinstance(item, dict):
                if item:
                    lines.append(f"{space}{safe_key}:")
                    lines.append(yaml_dump(item, indent + 2))
                else:
                    lines.append(f"{space}{safe_key}: {{}}")
            elif isinstance(item, list):
                if item:
                    lines.append(f"{space}{safe_key}:")
                    lines.append(yaml_dump(item, indent + 2))
                else:
                    lines.append(f"{space}{safe_key}: []")
            else:
                lines.append(f"{space}{safe_key}: {yaml_scalar(item)}")
        return "\n".join(lines)

    if isinstance(value, list):
        if not value:
            return f"{space}[]"
        lines = []
        for item in value:
            if isinstance(item, dict):
                if not item:
                    lines.append(f"{space}- {{}}")
                    continue
                first = True
                for key, child in item.items():
                    safe_key = str(key) if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_-]*", str(key)) else yaml_scalar(key)
                    prefix = f"{space}- " if first else f"{space}  "
                    if isinstance(child, dict):
                        if child:
                            lines.append(f"{prefix}{safe_key}:")
                            lines.append(yaml_dump(child, indent + 4))
                        else:
                            lines.append(f"{prefix}{safe_key}: {{}}")
                    elif isinstance(child, list):
                        if child:
                            lines.append(f"{prefix}{safe_key}:")
                            lines.append(yaml_dump(child, indent + 4))
                        else:
                            lines.append(f"{prefix}{safe_key}: []")
                    else:
                        lines.append(f"{prefix}{safe_key}: {yaml_scalar(child)}")
                    first = False
            elif isinstance(item, list):
                lines.append(f"{space}-")
                lines.append(yaml_dump(item, indent + 2))
            else:
                lines.append(f"{space}- {yaml_scalar(item)}")
        return "\n".join(lines)

    return f"{space}{yaml_scalar(value)}"


def write_yaml(path: Path, data: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml_dump(data) + "\n", encoding="utf-8")


def difficulty_for(lesson_number: int, question_number: int) -> str:
    score = lesson_number + question_number
