def validate_generated_bank(all_questions: List[Dict[str, Any]]) -> None:
    if len(all_questions) < 60:
        raise ValueError("Итоговый банк должен содержать минимум 60 вопросов.")

    ids = [question["id"] for question in all_questions]
    if len(ids) != len(set(ids)):
        duplicates = sorted({qid for qid in ids if ids.count(qid) > 1})
        raise ValueError(f"Повторяющиеся ID вопросов: {duplicates}")

    required = {
        "id",
        "lesson_id",
        "type",
        "difficulty",
        "prompt_ru",
        "prompt_kk",
        "rationale_ru",
        "rationale_kk",
        "randomization",
    }

    expected_lessons = {f"L{i:02d}" for i in range(1, 37)}
    covered_lessons = set()
    covered_tracks = set()

    for question in all_questions:
        missing = required - set(question)
        if missing:
            raise ValueError(f"{question.get('id', '<без ID>')}: нет полей {sorted(missing)}")

        if not re.fullmatch(r"Q-L\d{2}-\d{2}", question["id"]):
            raise ValueError(f"Некорректный ID: {question['id']}")

        if not question["id"].startswith(f"Q-{question['lesson_id']}-"):
            raise ValueError(f"ID не согласован с lesson_id: {question['id']}")

        has_answer = "correct_answer" in question
        has_rubric = "rubric_ru" in question and "rubric_kk" in question
        if not has_answer and not has_rubric:
            raise ValueError(f"{question['id']}: нет correct_answer или двуязычной rubric")

        has_options_ru = "options_ru" in question
        has_options_kk = "options_kk" in question
        if has_options_ru != has_options_kk:
            raise ValueError(f"{question['id']}: нарушен паритет options_ru/options_kk")
        if has_options_ru and len(question["options_ru"]) != len(question["options_kk"]):
            raise ValueError(f"{question['id']}: разное число RU/KK вариантов")

        covered_lessons.add(question["lesson_id"])
        covered_tracks.add(question["track"])

    if covered_lessons != expected_lessons:
        raise ValueError("Итоговый банк не покрывает все L01–L36.")
    if covered_tracks != set(TRACKS):
        raise ValueError("Итоговый банк не покрывает все треки.")


def main() -> None:
    ROOT.mkdir(parents=True, exist_ok=True)
    LESSONS_ROOT.mkdir(parents=True, exist_ok=True)

    all_questions: List[Dict[str, Any]] = []
    questions_by_lesson: Dict[str, List[Dict[str, Any]]] = {}

    for item in LESSONS:
        lesson_id = item["lesson_id"]
        lesson_dir = LESSONS_ROOT / lesson_id
        lesson_dir.mkdir(parents=True, exist_ok=True)

        questions = make_questions(item)
        questions_by_lesson[lesson_id] = questions
        all_questions.extend(questions)

        quiz = build_quiz(item, questions)
        write_yaml(lesson_dir / "quiz.yaml", quiz)

    validate_generated_bank(all_questions)
    final_bank = build_final_bank(all_questions)
    write_yaml(ROOT / "final-bank.yaml", final_bank)

    # QA запускается после создания quiz.yaml и final-bank.yaml.
    for item in LESSONS:
        lesson_dir = LESSONS_ROOT / item["lesson_id"]
        report = build_qa_report(item, lesson_dir)
        (lesson_dir / "qa-report.md").write_text(report, encoding="utf-8")

    enabled_count = sum(1 for item in LESSONS if item["mini_quiz"])
    disabled_count = len(LESSONS) - enabled_count
    print(
        f"Создано: 36 quiz.yaml ({enabled_count} enabled, {disabled_count} disabled), "
        f"final-bank.yaml с {len(all_questions)} вопросами и 36 qa-report.md."
    )


if __name__ == "__main__":
    main()